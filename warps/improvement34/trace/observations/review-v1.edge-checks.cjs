'use strict';
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),cp=require('node:child_process'),crypto=require('node:crypto');
const binary='C:/src/recur/.recur/evidence-binaries/improvement34-trace-v2/recur.exe';
const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'recur34-review-edge-'));
const meta=(...rows)=>'<!-- recur-trace-v1\n'+rows.join('\n')+'\n-->\n';
const write=(name,content)=>fs.writeFileSync(path.join(fixture,name),content);
const query=(pattern,args=[])=>{
 const r=cp.spawnSync(binary,['trace-id',pattern,'-d',fixture,'--json',...args],{encoding:'utf8'});
 return {code:r.status,report:r.stdout?JSON.parse(r.stdout):null,error:r.stderr};
};
const checks=[];
const check=(name,pass,observed)=>checks.push({name,pass,observed});
write('lab.separator.md','Reference capability_baseline.\n');
let r=query('capability_baseline',['--sep','_']);
check('custom separator followed by sentence punctuation stays discoverable',r.report.files.includes('lab.separator.md'),r);
write('lab.separator.md','Reference capability-baseline.\n');
r=query('capability-baseline',['--sep','-']);
check('hyphen separator followed by sentence punctuation stays discoverable',r.report.files.includes('lab.separator.md'),r);
write('lab.separator.md','Reference capability.baseline.\n');
r=query('capability.baseline');
check('dot separator followed by sentence punctuation',r.report.files.includes('lab.separator.md'),r);
write('lab.exact.md',meta('defines: capability.baseline','defines: capability.baseline.child','defines: capability.baseline_generator'));
r=query('capability.baseline',['--scope','lab.**','--declared']);
check('exact identity excludes child and underscore variant',r.report.declarations.length===1,r.report.declarations);
r=query('capability.baseline.**',['--scope','lab.**','--declared']);
check('explicit family includes child',r.report.declarations.some(x=>x.id==='capability.baseline.child'),r.report.declarations);
write('lab.case.md',meta('defines: Capability.Baseline'));
r=query('capability.baseline',['--scope','lab.case','--declared','--ignore-case']);
check('case insensitive filter preserves authored ID',r.report.declarations[0]?.id==='Capability.Baseline',r.report.declarations);
write('lab.unclosed.md','<!-- recur-trace-v1\ndefines: capability.baseline\n');
r=query('capability.baseline',['--scope','lab.unclosed','--declared']);
check('unterminated block contributes no authority',r.report.declarations.length===0 && r.report.diagnostics[0]?.code==='unterminated_metadata',r.report);
const sha=text=>crypto.createHash('sha256').update(text).digest('hex');
const artifact=(rev,file,text,context='dock')=>'artifact: '+JSON.stringify({id:'capability.baseline',context,revision:rev,path:file,sha256:sha(text)});
const pin=(expected,actual,context='dock')=>'requires: '+JSON.stringify({id:'capability.baseline',context,expected,actual});
write('one.txt','one');write('two.txt','two');
write('lab.pins.md',meta(artifact('R06','one.txt','one'),artifact('R06','two.txt','two'),pin('R06','R06')));
r=query('capability.baseline',['--scope','lab.pins','--declared']);
check('conflicting revision reports ambiguity and both sites',r.report.pins[0]?.reason==='ambiguous_artifact'&&r.report.diagnostics.some(d=>d.code==='conflicting_revision'&&d.sites.length===2),r.report);
write('lab.pins.md',meta(artifact('R06','one.txt','one'),artifact('R06','two.txt','two','other'),pin('R06','R06')));
r=query('capability.baseline',['--scope','lab.pins','--declared']);
check('explicit contexts isolate revision binding',r.report.pins[0]?.revision==='matched'&&r.report.pins[0]?.integrity==='matched',r.report);
write('lab.pins.md',meta(artifact('R06','one.txt','one'),pin('R06','R06')));
r=query('capability.baseline',['--scope','lab.pins','--declared','--max-entries','3']);
check('truncated scan cannot establish resolved revision',!r.report.coverage.complete&&r.report.pins[0]?.reason==='incomplete_scope',r.report);
const result={fixture,binary,checks};
fs.writeFileSync(path.join(__dirname,'edge-results.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({fixture,passed:checks.filter(x=>x.pass).length,failed:checks.filter(x=>!x.pass)},null,2));
